import type { AchievementDefinition } from './types'
import { ACHIEVEMENT_RARITY_XP } from './types'

function xp(rarity: AchievementDefinition['rarity'], override?: number) {
  return override ?? ACHIEVEMENT_RARITY_XP[rarity]
}

function def(
  partial: Omit<AchievementDefinition, 'xpReward'> & { xpReward?: number },
): AchievementDefinition {
  return { ...partial, xpReward: partial.xpReward ?? xp(partial.rarity) }
}

